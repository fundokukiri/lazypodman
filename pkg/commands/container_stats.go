// RecordedStats contains both the container stats we've received from podman, and our own derived stats  from those container stats. When configuring a graph, you're basically specifying the path of a value in this struct
type RecordedStats struct {
	ClientStats  ContainerStats
	DerivedStats DerivedStats
	RecordedAt   time.Time
}

// DerivedStats contains some useful stats that we've calculated based on the raw container stats that we got back from podman
type DerivedStats struct {
	CPUPercentage    float64
	MemoryPercentage float64
}

